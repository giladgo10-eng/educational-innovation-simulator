/**
 * פונקציית עזר לניקוי והזחת מחרוזת לפי תקן RFC-4180 ל-CSV
 */
function escapeCsv(str) {
  if (str === undefined || str === null) return '""';
  const s = String(str).replace(/"/g, '""');
  return `"` + s + `"`;
}

