/**
 * אישור הטעינה ע"י המשתמש (עם תמיכה בשימור שדות ריקים)
 */
function confirmImport() {
  if (!pendingImportData) {
    alert("לא נבחר קובץ תקין לטעינה.");
    return;
  }

  const saveModeRadio = document.querySelector('input[name="importSaveMode"]:checked');
  const shouldSaveToStorage = saveModeRadio ? saveModeRadio.value === "persistent" : false;

  const emptyModeRadio = document.querySelector('input[name="importEmptyMode"]:checked');
  const emptyMode = emptyModeRadio ? emptyModeRadio.value : "preserve";

  if (emptyMode === "preserve" && pendingImportData._providedKeys && pendingImportData._providedKeys.length > 0) {
    // מיזוג מבוקר: שמור על נתונים קיימים עבור שדות שלא סופקו בקובץ
    const merged = JSON.parse(JSON.stringify(appData));
    for (const key of pendingImportData._providedKeys) {
      const val = getDeepValue(pendingImportData, key);
      if (val !== undefined) {
        setDeepValue(merged, key, val);
      }
    }
    if (pendingImportData._providedKeys.includes("stage2.neighborhoods") && Array.isArray(pendingImportData.stage2?.neighborhoods)) {
      merged.stage2.neighborhoods = pendingImportData.stage2.neighborhoods;
    }
    if (pendingImportData._providedKeys.includes("stage3.programs") && Array.isArray(pendingImportData.stage3?.programs)) {
      merged.stage3.programs = pendingImportData.stage3.programs;
    }
    merged.isDemo = false;
    merged.lastImported = new Date().toISOString();
    appData = merged;
  } else {
    // דריסה מלאה לפי בחירת המשתמש
    const fullData = JSON.parse(JSON.stringify(pendingImportData));
    delete fullData._providedKeys;
    delete fullData._lineErrors;
    delete fullData._lineWarnings;
    appData = fullData;
  }

  if (shouldSaveToStorage) {
    saveData(false);
  }

  // עדכון ממשק וחישובים
  currentStep = 1;
  populateFormFields();
  updateBudgetAndSpaceCalculations();
  renderCurrentStep();
  renderExecutiveSummary();

  closeImportModal();

  const msg = shouldSaveToStorage ? 
    "הנתונים נטענו בהצלחה ונשמרו כפרויקט הפעיל בדפדפן!" : 
    "הנתונים נטענו להרצה נוכחית (שינויים יישמרו ל-LocalStorage רק בלחיצה על 'שמור עבודה').";

  showToast(msg, "success");
}